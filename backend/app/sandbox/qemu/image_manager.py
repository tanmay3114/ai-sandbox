"""Guest image verification, SHA-256 provenance checks, and disposable overlay management."""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import stat
import subprocess
import uuid
from dataclasses import dataclass
from pathlib import Path

from app.core.config import SandboxSettings, settings
from app.core.exceptions import QemuEngineError
from app.sandbox.qemu.config import QemuVmConfig, validate_safe_qemu_path

UNIX_PATH_MAX_SAFE = 96  # macOS AF_UNIX sun_path limit is 104 bytes including NUL


@dataclass(frozen=True, slots=True)
class PreparedVmStorage:
    """Per-execution private runtime paths and disposable disk overlay."""

    sandbox_id: str
    execution_id: str
    runtime_dir: Path
    socket_dir: Path
    socket_path: Path
    overlay_path: Path
    pidfile_path: Path
    console_log_path: Path
    metadata_path: Path


def compute_sha256(path: Path) -> str:
    """Stream a file in 64 KB chunks and return its lowercase SHA-256 hex digest."""
    digest = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            chunk = f.read(64 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def _verify_immutable_asset_file(
    path: Path,
    label: str,
    expected_sha256: str | None = None,
) -> None:
    """Ensure a guest boot asset exists, is a regular file (not symlink), and matches checksum."""
    validate_safe_qemu_path(path, label)
    try:
        st = os.lstat(path)
    except FileNotFoundError as exc:
        raise QemuEngineError(f"Required QEMU guest asset {label} not found at '{path}'") from exc
    except OSError as exc:
        raise QemuEngineError(f"Unable to inspect QEMU guest asset {label}: {exc}") from exc

    if stat.S_ISLNK(st.st_mode):
        raise QemuEngineError(f"QEMU guest asset {label} must not be a symbolic link")
    if not stat.S_ISREG(st.st_mode):
        raise QemuEngineError(f"QEMU guest asset {label} must be a regular file")
    if st.st_size <= 0:
        raise QemuEngineError(f"QEMU guest asset {label} is empty")
    if st.st_mode & stat.S_IWOTH:
        mode_oct = oct(st.st_mode & 0o777)
        raise QemuEngineError(
            f"QEMU guest asset {label} has insecure world-writable permissions ({mode_oct})"
        )

    if expected_sha256:
        actual = compute_sha256(path)
        if actual.lower() != expected_sha256.strip().lower():
            raise QemuEngineError(
                f"SHA-256 checksum mismatch for {label}: expected "
                f"{expected_sha256.lower()}, got {actual}"
            )


def _ensure_secure_private_dir(path: Path) -> None:
    """Create or verify a directory owned by current UID with strict 0700 permissions."""
    path.mkdir(parents=True, exist_ok=True, mode=0o700)
    st = os.lstat(path)
    if stat.S_ISLNK(st.st_mode) or not stat.S_ISDIR(st.st_mode):
        raise QemuEngineError(f"Runtime path '{path}' must be a real directory, not a symlink")
    if st.st_uid != os.getuid():
        raise QemuEngineError(f"Runtime directory '{path}' is not owned by the current user")
    os.chmod(path, 0o700)


class QemuImageManager:
    """Manages immutable ARM64 guest image assets and disposable per-execution overlays."""

    def __init__(self, config: SandboxSettings = settings) -> None:
        self.config = config

    def _load_manifest_digests(self, image_dir: Path) -> dict[str, str]:
        """Read optional manifest.json checksums generated by guest/scripts/build_guest_image.sh."""
        manifest_path = image_dir / "manifest.json"
        if not manifest_path.is_file() or manifest_path.is_symlink():
            return {}
        try:
            data = json.loads(manifest_path.read_text(encoding="utf-8"))
            if isinstance(data, dict) and isinstance(data.get("sha256"), dict):
                return {str(k): str(v) for k, v in data["sha256"].items()}
        except Exception as exc:
            raise QemuEngineError(f"Corrupted guest image manifest.json: {exc}") from exc
        return {}

    def verify_guest_assets(self, vm_cfg: QemuVmConfig) -> None:
        """Validate kernel, initramfs, and optional base rootfs image before booting a VM."""
        manifest_hashes = self._load_manifest_digests(self.config.QEMU_IMAGE_DIR)

        kernel_sha = self.config.QEMU_KERNEL_SHA256 or manifest_hashes.get(vm_cfg.kernel_path.name)
        initrd_sha = self.config.QEMU_INITRD_SHA256 or manifest_hashes.get(vm_cfg.initrd_path.name)

        _verify_immutable_asset_file(vm_cfg.kernel_path, "kernel", expected_sha256=kernel_sha)
        _verify_immutable_asset_file(vm_cfg.initrd_path, "initramfs", expected_sha256=initrd_sha)

        if vm_cfg.base_image_path is not None and (
            self.config.QEMU_BASE_IMAGE_PATH is not None or vm_cfg.base_image_path.exists()
        ):
            base_sha = self.config.QEMU_BASE_IMAGE_SHA256 or manifest_hashes.get(
                vm_cfg.base_image_path.name
            )
            _verify_immutable_asset_file(
                vm_cfg.base_image_path,
                "base_image",
                expected_sha256=base_sha,
            )

    def prepare_execution_storage(
        self,
        *,
        sandbox_id: str,
        execution_id: str | None = None,
        vm_cfg: QemuVmConfig,
    ) -> PreparedVmStorage:
        """Create a private 0700 per-execution runtime directory and disposable qcow2 overlay."""
        self.verify_guest_assets(vm_cfg)
        _ensure_secure_private_dir(vm_cfg.runtime_dir)

        exec_id = execution_id or uuid.uuid4().hex[:12]
        short_token = f"vm-{exec_id[:12]}"
        exec_runtime_dir = vm_cfg.runtime_dir / short_token

        try:
            os.mkdir(exec_runtime_dir, 0o700)
        except FileExistsError:
            exec_id = uuid.uuid4().hex[:12]
            short_token = f"vm-{exec_id}"
            exec_runtime_dir = vm_cfg.runtime_dir / short_token
            os.mkdir(exec_runtime_dir, 0o700)
        os.chmod(exec_runtime_dir, 0o700)

        candidate_socket = exec_runtime_dir / "a.sock"
        if len(str(candidate_socket).encode("utf-8")) <= UNIX_PATH_MAX_SAFE:
            socket_dir = exec_runtime_dir
            socket_path = candidate_socket
        else:
            short_base = Path(f"/tmp/aisbx-{os.getuid()}")
            _ensure_secure_private_dir(short_base)
            socket_dir = short_base / short_token
            os.mkdir(socket_dir, 0o700)
            os.chmod(socket_dir, 0o700)
            socket_path = socket_dir / "a.sock"

        overlay_path = exec_runtime_dir / "overlay.qcow2"
        pidfile_path = exec_runtime_dir / "qemu.pid"
        console_log_path = exec_runtime_dir / "console.log"
        metadata_path = exec_runtime_dir / "vm_metadata.json"

        try:
            self._create_qcow2_overlay(
                vm_cfg=vm_cfg,
                overlay_path=overlay_path,
            )
        except Exception:
            self._remove_storage_dirs(exec_runtime_dir, socket_dir)
            raise

        return PreparedVmStorage(
            sandbox_id=sandbox_id,
            execution_id=exec_id,
            runtime_dir=exec_runtime_dir,
            socket_dir=socket_dir,
            socket_path=socket_path,
            overlay_path=overlay_path,
            pidfile_path=pidfile_path,
            console_log_path=console_log_path,
            metadata_path=metadata_path,
        )

    def _create_qcow2_overlay(self, *, vm_cfg: QemuVmConfig, overlay_path: Path) -> None:
        """Create a disposable per-execution qcow2 disk using qemu-img without shell invocation."""
        validate_safe_qemu_path(overlay_path, "overlay_path")
        has_backing = (
            vm_cfg.base_image_path is not None
            and vm_cfg.base_image_path.is_file()
            and not vm_cfg.base_image_path.is_symlink()
        )
        if has_backing and vm_cfg.base_image_path is not None:
            argv = [
                vm_cfg.qemu_img_binary,
                "create",
                "-f",
                "qcow2",
                "-F",
                "qcow2",
                "-b",
                str(vm_cfg.base_image_path),
                str(overlay_path),
                vm_cfg.disk_size,
            ]
        else:
            argv = [
                vm_cfg.qemu_img_binary,
                "create",
                "-f",
                "qcow2",
                str(overlay_path),
                vm_cfg.disk_size,
            ]

        try:
            proc = subprocess.run(
                argv,
                capture_output=True,
                text=True,
                timeout=10.0,
                check=False,
            )
        except FileNotFoundError as exc:
            raise QemuEngineError(
                f"QEMU image utility '{vm_cfg.qemu_img_binary}' not found on host"
            ) from exc
        except subprocess.TimeoutExpired as exc:
            raise QemuEngineError("Timed out creating disposable qcow2 VM overlay") from exc
        except OSError as exc:
            raise QemuEngineError(f"Failed to execute '{vm_cfg.qemu_img_binary}': {exc}") from exc

        if proc.returncode != 0 or not overlay_path.is_file():
            stderr = (proc.stderr or proc.stdout or "").strip()
            raise QemuEngineError(f"qemu-img failed to create disposable overlay: {stderr}")

        os.chmod(overlay_path, 0o600)

    def cleanup_storage(self, storage: PreparedVmStorage) -> bool:
        """Remove the per-execution overlay, socket directory, and runtime directory."""
        return self._remove_storage_dirs(storage.runtime_dir, storage.socket_dir)

    @staticmethod
    def _remove_storage_dirs(runtime_dir: Path, socket_dir: Path) -> bool:
        success = True
        for target in (socket_dir, runtime_dir):
            if not target.exists() and not target.is_symlink():
                continue
            try:
                if target.is_symlink() or target.is_file():
                    target.unlink()
                else:
                    shutil.rmtree(target)
            except OSError:
                success = False
        return success
